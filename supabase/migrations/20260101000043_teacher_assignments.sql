-- Doc 16 Milestone 2 (Core Teacher Workflow): assignment creation with
-- notification fan-out, and retraction with audit logging.
--
-- Attendance and Score entry need NO new functions here -- both tables
-- already have complete teacher RLS policies (060_academic_activity.sql)
-- that permit direct client inserts/upserts with no atomicity concern (each
-- row is independent, same reasoning academic-setup's plain Class/Subject/
-- Term inserts already use). Assignment creation is different: it must also
-- write a Notification row per enrolled family in the same transaction, and
-- Notification has no generic client insert policy (070_notifications.sql --
-- "most rows... are generated by the background job / business-logic
-- layer"), so this has to go through a SECURITY DEFINER function regardless.
--
-- Doc 8 says bulk notification fan-out belongs in the background job queue,
-- not synchronously in the request path, and Doc 23 Section 4 describes that
-- queue as Supabase Edge Functions + pg_cron + Database Webhooks. None of
-- that infrastructure has been stood up in this project (same gap CSV bulk
-- import hit, and the user's resolution there was "build it synchronously
-- now" -- same call applies here, at the same project stage: Doc 3 Section 5
-- explicitly says the current architecture is "sufficient" through "launch
-- -> low thousands of schools," which covers a single pilot school's one
-- class worth of families many times over). The existing
-- assignment_enqueue_notification trigger (migration 033) still fires and
-- still records a Job row -- that stays as the audit trail / outbox record
-- Doc 23 Section 4 asks for, it's just that nothing asynchronous consumes it
-- yet, because delivery already happened synchronously in this same
-- transaction.
create or replace function teacher_create_assignment(
  p_class_id uuid,
  p_subject_id uuid,
  p_title text,
  p_instructions text,
  p_available_at timestamptz,
  p_due_at timestamptz default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_teacher_id uuid := auth_teacher_id();
  v_school_id uuid := auth_school_id();
  v_assignment_id uuid;
  v_class_name text;
  v_subject_name text;
begin
  if auth_app_role() <> 'teacher' then
    raise exception 'only a teacher can create an assignment';
  end if;

  if not exists (
    select 1 from "TeacherClassAssignment"
    where teacher_id = v_teacher_id and class_id = p_class_id and subject_id = p_subject_id
  ) then
    raise exception 'you are not assigned to this class/subject';
  end if;

  insert into "Assignment" (
    class_id, subject_id, teacher_id, school_id, title, instructions, available_at, due_at, status
  )
  values (p_class_id, p_subject_id, v_teacher_id, v_school_id, p_title, p_instructions, p_available_at, p_due_at, 'Published')
  returning assignment_id into v_assignment_id;

  select name into v_class_name from "Class" where class_id = p_class_id;
  select name into v_subject_name from "Subject" where subject_id = p_subject_id;

  -- One Notification per family currently linked to a student in this
  -- class, deduplicated (a guardian with two children in the same class
  -- should get one notification, not two).
  insert into "Notification" (membership_id, source_type, category, related_entity_id, message_text)
  select distinct fsr.membership_id, 'system', 'assignment', v_assignment_id,
    format('New assignment: %s (%s - %s)', p_title, v_class_name, v_subject_name)
  from "ClassMembership" cm
  join "SchoolEnrollment" se on se.enrollment_id = cm.enrollment_id and se.status = 'Active'
  join "FamilyStudentRelationship" fsr on fsr.platform_student_id = se.platform_student_id
  join "FamilyMembership" fm on fm.membership_id = fsr.membership_id and fm.status = 'Active'
  where cm.class_id = p_class_id and cm.end_date is null;

  return v_assignment_id;
end;
$$;

revoke all on function teacher_create_assignment(uuid, uuid, text, text, timestamptz, timestamptz) from public;
grant execute on function teacher_create_assignment(uuid, uuid, text, text, timestamptz, timestamptz) to authenticated;

-- Doc 13 #1 Screen 4: "[Retract] option (not delete) -- confirmation
-- required, logs to audit." Status flip + AuditLog insert in one
-- transaction -- AuditLog itself has an open insert policy for any
-- authenticated role at their own school, but bundling it here keeps this
-- consistent with the rest of the codebase's "a write and the record of
-- that write happen in one function call" rule rather than reintroducing
-- the two-call atomicity gap fixed elsewhere (migration 040).
create or replace function teacher_retract_assignment(p_assignment_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_teacher_id uuid := auth_teacher_id();
  v_school_id uuid := auth_school_id();
  v_row "Assignment"%rowtype;
begin
  if auth_app_role() <> 'teacher' then
    raise exception 'only a teacher can retract an assignment';
  end if;

  select * into v_row from "Assignment" where assignment_id = p_assignment_id;
  if v_row.assignment_id is null or v_row.teacher_id <> v_teacher_id then
    raise exception 'assignment not found';
  end if;
  if v_row.status = 'Retracted' then
    raise exception 'assignment is already retracted';
  end if;

  update "Assignment" set status = 'Retracted' where assignment_id = p_assignment_id;

  insert into "AuditLog" (school_id, actor_id, actor_role, action_type, target_entity, target_id, details)
  values (
    v_school_id,
    v_teacher_id,
    'teacher',
    'assignment_retracted',
    'Assignment',
    p_assignment_id::text,
    jsonb_build_object('title', v_row.title)
  );
end;
$$;

revoke all on function teacher_retract_assignment(uuid) from public;
grant execute on function teacher_retract_assignment(uuid) to authenticated;
